"""Apps do Menu Iniciar na voz: "PC, abre o Spotify" com o Spotify da Microsoft Store."""
import unittest

import startapps
import voice

RAW = [
    {"Name": "Spotify", "AppID": "SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify"},
    {"Name": "WhatsApp", "AppID": "5319275A.WhatsAppDesktop_cv1g1gvanyjgm!App"},
    {"Name": "Uninstall Zoom Workplace", "AppID": "Microsoft.AutoGenerated.{A149}"},
    {"Name": "Desinstalar a Tradução", "AppID": "{7C5A}\\GameVicio\\Desinstalar.exe"},
    {"Name": "Steam Support Center", "AppID": "http://support.steampowered.com/"},
    {"Name": "Calculadora", "AppID": "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"},
]


class StartAppsTest(unittest.TestCase):
    def test_tira_desinstaladores_e_links(self):
        names = [n for _a, n in startapps.clean(RAW)]
        self.assertEqual(names, ["Spotify", "WhatsApp", "Calculadora"])

    def cat(self):
        return voice.Catalog([("calc", "Calculadora")], [], [], startapps.clean(RAW))

    def test_voz_acha_o_spotify_da_loja(self):
        r = voice.parse_command("abrir o spotify", self.cat())
        self.assertEqual(r["action"], "app.launch")
        self.assertEqual(r["p"]["id"], "start:SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify")

    def test_atalho_do_config_ganha_empate(self):
        r = voice.parse_command("abre a calculadora", self.cat())
        self.assertEqual(r["p"]["id"], "calc")


if __name__ == "__main__":
    unittest.main()
